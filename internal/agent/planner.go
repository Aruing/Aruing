// 规划模块负责根据问题结构和已确认目标生成候选猜想与待执行任务
//
// 真实现见大模型规划器：同一计划边界，单次大模型调用，工具规格来自注册表
// 测试替身见测试假规划器
// 调用方必须先完成目标定位，返回的猜想和任务会绑定到同一次运行
package agent

import (
	"aruing/internal/core"
)

// 汇总一次规划产生的候选猜想和待执行任务，只作为模块间返回值
// 该结构不是新的持久化实体，调用方应分别保存其中的核心数据
type Plan struct {
	// 本轮需要通过证据验证的候选原因列表
	Hypotheses []core.Hypothesis
	// 为定位信息或验证猜想而生成的工具任务列表
	Tasks []core.Task
	// 可选：证据不足以继续且缺口信息用户知道（故障时间、近期变更等）时提议澄清；
	// 与任务/猜想互斥（同给为规划错误，由编排拒绝），镜像 resolver 的 clarify 意图
	Clarify *ClarifyRequest
}
